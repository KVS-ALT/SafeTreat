export type IconName = keyof typeof LINE;

/** Turn a grid of '#' into one SVG path of 1×1 squares. */
export function gridPath(rows: string[], char = "#") {
  let d = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === char) d += `M${x} ${y}h1v1h-1z`;
  });
  return d;
}

const PIXEL_PATHS = Object.fromEntries(Object.entries(PIXEL).map(([k, rows]) => [k, gridPath(rows)]));

export default function Icon({ name, size = 18, className = "", label }: { name: IconName; size?: number; className?: string; label?: string }) {
  const a11y = label ? { role: "img", "aria-label": label } : { "aria-hidden": true };
  return (
    <span className={`inline-flex shrink-0 ${className}`} {...a11y}>
      <svg className="icon-line" width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor"
        strokeWidth={1.75} strokeLinecap="round" strokeLinejoin="round">
        {LINE[name].map((d, i) => <path key={i} d={d} />)}
      </svg>
      <svg className="icon-pixel" width={size} height={size} viewBox="-1 -1 12 12" shapeRendering="crispEdges" fill="currentColor">
        <path d={PIXEL_PATHS[name] ?? PIXEL_PATHS.star} />
      </svg>
    </span>
  );
}
